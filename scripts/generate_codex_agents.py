#!/usr/bin/env python3
"""Generate project-scoped Codex profiles from the maintained role instructions."""
import argparse
import json
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
TEMPLATE = ROOT / "assets/plantilla"

# Model routing is a studio default, not a measured quality guarantee.
MODEL_SETTINGS = {
    "arquitecto": ("gpt-6.1-sol", "medium"),
    "disenador-juego": ("gpt-6.1-sol", "medium"),
    "ingeniero-gameplay": ("gpt-6.1-sol", "medium"),
    "ingeniero-ui": ("gpt-6.1-sol", "medium"),
    "artista-tecnico": ("gpt-6.1-sol", "medium"),
    "ingeniero-plataforma": ("gpt-6.1-sol", "medium"),
    "revisor-codigo": ("gpt-6.1-sol", "medium"),
    "revisor-diseno": ("gpt-6.1-sol", "medium"),
    "director-arte": ("gpt-6.1-sol", "medium"),
    "revisor-jugabilidad": ("gpt-6.1-sol", "medium"),
    "qa-tester": ("gpt-6.1-sol", "medium"),
    "analista-balance": ("gpt-6.1-sol", "medium"),
    "disenador-sonido": ("gpt-6.1-sol", "medium"),
    "investigador-juegos": ("gpt-6-luna", "medium"),
    "disenador-contenido": ("gpt-6-luna", "low"),
    "playtester": ("gpt-6-luna", "low"),
    "responsable-lanzamiento": ("gpt-6-luna", "low"),
}


def render_profiles(template=TEMPLATE):
    """Return complete TOML profiles without changing files."""
    sources = {path.stem: path for path in (template / ".claude/agents").glob("*.md")}
    if sources.keys() != MODEL_SETTINGS.keys():
        raise ValueError("Every role must have an explicit Codex model assignment")
    profiles = {}
    for role, source in sorted(sources.items()):
        _, header, instructions = source.read_text(encoding="utf-8").split("---", 2)
        metadata = yaml.safe_load(header)
        if metadata["name"] != role:
            raise ValueError(f"Role name does not match filename: {source}")
        model, effort = MODEL_SETTINGS[role]
        if effort not in ("medium", "low"):
            raise ValueError(f"Unsupported studio reasoning effort: {role}: {effort}")
        # JSON string escaping is valid for these TOML basic string values.
        fields = {
            "name": role,
            "description": metadata["description"],
            "model": model,
            "model_reasoning_effort": effort,
            "developer_instructions": instructions.strip().replace("CLAUDE.md", "AGENTS.md"),
        }
        profiles[role] = "# Generated by scripts/generate_codex_agents.py; edit source roles and regenerate.\n" + "".join(
            f"{key} = {json.dumps(value, ensure_ascii=False)}\n" for key, value in fields.items()
        )
    return profiles


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if generated profiles need updating")
    args = parser.parse_args()
    destination = TEMPLATE / ".codex/agents"
    profiles = render_profiles()
    expected = {f"{role}.toml" for role in profiles}
    existing = {path.name for path in destination.glob("*.toml")}
    if existing - expected:
        parser.error("Unexpected Codex profiles; review them before regeneration")
    stale = []
    for role, content in profiles.items():
        path = destination / f"{role}.toml"
        if not path.is_file() or path.read_text(encoding="utf-8") != content:
            stale.append(role)
            if not args.check:
                destination.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8", newline="\n")
    if args.check and stale:
        parser.exit(1, f"Stale Codex profiles: {', '.join(stale)}\n")
    print(f"Codex profiles {'checked' if args.check else 'generated'}: {len(profiles)}")


if __name__ == "__main__":
    main()
